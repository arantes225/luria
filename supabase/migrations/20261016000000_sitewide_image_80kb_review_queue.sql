-- Enforce an 80 KiB image cap and route images below 600 px (short edge) to Admin review.
create table if not exists public.low_resolution_image_review_queue (
  id bigint generated by default as identity primary key,
  bucket_id text not null,
  object_name text not null,
  owner_id uuid not null,
  source_page text not null default '/',
  width integer not null check (width > 0),
  height integer not null check (height > 0),
  size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 81920),
  review_status text not null default 'pending' check (review_status in ('pending','reviewed')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid,
  unique (bucket_id, object_name)
);
alter table public.low_resolution_image_review_queue enable row level security;
drop policy if exists low_resolution_image_admin_select on public.low_resolution_image_review_queue;
create policy low_resolution_image_admin_select on public.low_resolution_image_review_queue
  for select to authenticated using (public.is_admin());
drop policy if exists low_resolution_image_admin_update on public.low_resolution_image_review_queue;
create policy low_resolution_image_admin_update on public.low_resolution_image_review_queue
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
grant select, update on public.low_resolution_image_review_queue to authenticated;
grant usage, select on sequence public.low_resolution_image_review_queue_id_seq to authenticated;

create or replace function public.queue_low_resolution_image(
  p_bucket_id text,
  p_object_name text,
  p_width integer,
  p_height integer,
  p_size_bytes bigint,
  p_source_page text
) returns jsonb
language plpgsql
security definer
set search_path = public, storage
as $$
declare
  v_object storage.objects%rowtype;
begin
  if auth.uid() is null then raise exception 'Sessão necessária'; end if;
  if p_bucket_id not in ('apostila-media','docmap','docmap-assets','flashcard-media','study-room-attachments') then
    raise exception 'Bucket não permitido';
  end if;
  if p_width is null or p_height is null or least(p_width,p_height) >= 600 then
    raise exception 'Imagem não se enquadra na fila de baixa resolução';
  end if;
  if p_size_bytes is null or p_size_bytes <= 0 or p_size_bytes > 81920 then
    raise exception 'Tamanho de imagem inválido';
  end if;

  select * into v_object from storage.objects
   where bucket_id = p_bucket_id and name = p_object_name;
  if not found or v_object.owner_id::text <> auth.uid()::text then
    raise exception 'Imagem não pertence ao usuário autenticado';
  end if;
  if coalesce(v_object.metadata->>'mimetype','') not like 'image/%'
     or coalesce(nullif(v_object.metadata->>'size','')::bigint, p_size_bytes) <> p_size_bytes then
    raise exception 'Metadados da imagem não conferem';
  end if;

  insert into public.low_resolution_image_review_queue
    (bucket_id, object_name, owner_id, source_page, width, height, size_bytes, review_status, reviewed_at, reviewed_by)
  values
    (p_bucket_id, p_object_name, auth.uid(), left(coalesce(p_source_page,'/'),160),
     p_width, p_height, p_size_bytes, 'pending', null, null)
  on conflict (bucket_id, object_name) do update
    set owner_id = excluded.owner_id, source_page = excluded.source_page,
        width = excluded.width, height = excluded.height, size_bytes = excluded.size_bytes,
        review_status = 'pending', created_at = now(), reviewed_at = null, reviewed_by = null;
  return jsonb_build_object('queued', true, 'review_status', 'pending');
end;
$$;
revoke all on function public.queue_low_resolution_image(text,text,integer,integer,bigint,text) from public, anon;
grant execute on function public.queue_low_resolution_image(text,text,integer,integer,bigint,text) to authenticated;

-- Storage must also protect against clients that bypass the browser compressor.
-- Mixed-content buckets keep their existing PDF/non-image allowance.
drop policy if exists luria_image_size_cap_insert on storage.objects;
create policy luria_image_size_cap_insert on storage.objects as restrictive
  for insert to authenticated with check (
    bucket_id not in ('apostila-media','docmap','docmap-assets','flashcard-media','study-room-attachments')
    or (
      coalesce(metadata->>'mimetype','') not like 'image/%'
      and lower(name) !~ '\\.(avif|gif|jpe?g|png|svg|webp|bmp|tiff?)$'
    )
    or (
      coalesce(metadata->>'size','') ~ '^[0-9]+$'
      and (metadata->>'size')::bigint <= 81920
    )
  );
drop policy if exists luria_image_size_cap_update on storage.objects;
create policy luria_image_size_cap_update on storage.objects as restrictive
  for update to authenticated using (
    bucket_id not in ('apostila-media','docmap','docmap-assets','flashcard-media','study-room-attachments')
    or (
      coalesce(metadata->>'mimetype','') not like 'image/%'
      and lower(name) !~ '\\.(avif|gif|jpe?g|png|svg|webp|bmp|tiff?)$'
    )
    or (
      coalesce(metadata->>'size','') ~ '^[0-9]+$'
      and (metadata->>'size')::bigint <= 81920
    )
  ) with check (
    bucket_id not in ('apostila-media','docmap','docmap-assets','flashcard-media','study-room-attachments')
    or (
      coalesce(metadata->>'mimetype','') not like 'image/%'
      and lower(name) !~ '\\.(avif|gif|jpe?g|png|svg|webp|bmp|tiff?)$'
    )
    or (
      coalesce(metadata->>'size','') ~ '^[0-9]+$'
      and (metadata->>'size')::bigint <= 81920
    )
  );

drop policy if exists luria_admin_read_queued_low_resolution_images on storage.objects;
create policy luria_admin_read_queued_low_resolution_images on storage.objects
  for select to authenticated using (
    public.is_admin() and exists (
      select 1 from public.low_resolution_image_review_queue q
       where q.bucket_id = storage.objects.bucket_id and q.object_name = storage.objects.name
    )
  );

update storage.buckets set file_size_limit = 81920
 where id = 'apostila-media';
