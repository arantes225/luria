<p>Esses imunocomplexos subepiteliais ativam poderosamente a <strong>via alternativa do sistema complemento</strong>. A clivagem de C3 em C3a (anafilatoxina) atrai neutrófilos que liberam elastases e espécies reativas de oxigênio, fragmentando as células endoteliais e a MBG (o que permite o extravasamento mecânico de hemácias e formação de fendas de hematúria glomerular). A oclusão dos lúmens capilares pela proliferação celular endotelial e mesangial provoca <strong>queda abrupta e dramática da Taxa de Filtração Glomerular (TFG)</strong>, mantendo a reabsorção tubular de sódio normal ou aumentada nos túbulos distais intactos. Instala-se uma <strong>retenção primária hidrossalina severa</strong>, expansão volêmica intravascular maciça, hipertensão arterial aguda hipervolêmica e sobrecarga circulatória com edema.</p>

